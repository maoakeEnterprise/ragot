"""Pydantic data models of the RAG system."""
from pydantic import BaseModel, Field
import uuid


class MinimalSource(BaseModel):
    """Location of a snippet in the corpus.

    Attributes:
        file_path: Path of the file, exactly as in the corpus.
        first_character_index: Index of the first character.
        last_character_index: Index right after the last character.
    """

    file_path: str
    first_character_index: int
    last_character_index: int


class Chunk(MinimalSource):
    """A source location with its text.

    Attributes:
        content: Text of the chunk.
    """

    content: str


class ChunkIndex(BaseModel):
    """Every chunk of the corpus, saved in ``chunks.json``.

    Attributes:
        chunks: Chunks in the same order as the BM25 document ids.
    """

    chunks: list[Chunk]


class UnansweredQuestion(BaseModel):
    """A question without its reference answer.

    Attributes:
        question_id: Unique id, a random UUID by default.
        question: Text of the question.
    """

    question_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    question: str


class AnsweredQuestion(UnansweredQuestion):
    """A question with its reference sources and answer.

    Attributes:
        sources: Ground-truth source locations.
        answer: Reference answer.
    """

    sources: list[MinimalSource]
    answer: str


class RagDataset(BaseModel):
    """A dataset of questions.

    Attributes:
        rag_questions: Answered or unanswered questions.
    """

    rag_questions: list[AnsweredQuestion | UnansweredQuestion]


class MinimalSearchResults(BaseModel):
    """Retrieved sources for one question.

    Attributes:
        question_id: Id of the question.
        question: Text of the question.
        retrieved_sources: Top-k sources, best first.
    """

    question_id: str
    question: str
    retrieved_sources: list[MinimalSource]


class MinimalAnswer(MinimalSearchResults):
    """Retrieved sources and generated answer for one question.

    Attributes:
        answer: Answer generated by the LLM.
    """

    answer: str


class StudentSearchResults(BaseModel):
    """Output of ``search_dataset``.

    Attributes:
        search_results: Search results of every question.
        k: Number of sources requested per question.
    """

    search_results: list[MinimalSearchResults]
    k: int


class StudentSearchResultsAndAnswer(BaseModel):
    """Output of ``answer_dataset``.

    Attributes:
        search_results: Search results and answer of every question.
        k: Number of sources requested per question.
    """

    search_results: list[MinimalAnswer]
    k: int
